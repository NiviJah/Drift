/// <reference types="node" />
/**
 * Renders every sound recipe, encodes it to MP3 and writes a typed
 * manifest the app imports.
 *
 *   node synth/build.ts                 # build everything
 *   node synth/build.ts --only rain,fan # rebuild a subset
 *   node synth/build.ts --wav <dir>     # also keep the raw WAVs (for auditioning)
 *
 * Requires ffmpeg on PATH.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { circularPad, dbToGain, encodeWav, mulberry32, normalize, peak, rms, seedFrom } from './dsp.ts';
import type { Stereo } from './dsp.ts';
import { allBeds, allOneShots } from './recipes/index.ts';

export const SAMPLE_RATE = 48000;
/** Circular padding on each side of a loop (seconds). See circularPad(). */
export const LOOP_PAD_SECONDS = 0.1;
// MP3 decodes everywhere (iOS, Android, every browser); circular padding makes it gapless.
const BITRATE = '160k';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets', 'sounds');
const manifestPath = join(root, 'src', 'audio', 'generated', 'manifest.ts');

const args = process.argv.slice(2);
const onlyArg = args.indexOf('--only');
const only = onlyArg >= 0 ? new Set(args[onlyArg + 1].split(',')) : null;
const wavArg = args.indexOf('--wav');
const wavDir = wavArg >= 0 ? resolve(args[wavArg + 1]) : null;

function encode(buf: Stereo, name: string, tmp: string): void {
  const wav = join(tmp, `${name}.wav`);
  writeFileSync(wav, encodeWav(buf, SAMPLE_RATE));
  if (wavDir) copyFileSync(wav, join(wavDir, `${name}.wav`));
  execFileSync('ffmpeg', [
    '-hide_banner',
    '-loglevel',
    'error',
    '-y',
    '-i',
    wav,
    '-c:a',
    'libmp3lame',
    '-b:a',
    BITRATE,
    '-compression_level',
    '0',
    '-ar',
    String(SAMPLE_RATE),
    '-map_metadata',
    '-1',
    '-id3v2_version',
    '0',
    join(outDir, `${name}.mp3`),
  ]);
}

/**
 * Loop-seam discontinuity: the second difference across the seam relative to
 * the 90th percentile of second differences elsewhere (≲ 1 means inaudible).
 */
function seamRatio(buf: Stereo): number {
  let worst = 0;
  for (const ch of buf) {
    const n = ch.length;
    const d2: number[] = [];
    for (let i = 2; i < n; i += 97) d2.push(Math.abs(ch[i] - 2 * ch[i - 1] + ch[i - 2]));
    d2.sort((a, b) => a - b);
    const typical = d2[Math.floor(d2.length * 0.9)] || 1e-9;
    const seam = Math.max(Math.abs(ch[0] - 2 * ch[n - 1] + ch[n - 2]), Math.abs(ch[1] - 2 * ch[0] + ch[n - 1]));
    worst = Math.max(worst, seam / typical);
  }
  return worst;
}

function main(): void {
  mkdirSync(outDir, { recursive: true });
  mkdirSync(dirname(manifestPath), { recursive: true });
  if (wavDir) mkdirSync(wavDir, { recursive: true });
  const tmp = mkdtempSync(join(tmpdir(), 'synth-'));
  const pad = Math.floor(LOOP_PAD_SECONDS * SAMPLE_RATE);

  try {
    for (const recipe of allBeds) {
      if (only && !only.has(recipe.id)) continue;
      const started = Date.now();
      const frames = Math.round(recipe.seconds * SAMPLE_RATE);
      const buf = recipe.render(SAMPLE_RATE, frames, mulberry32(seedFrom(recipe.id)));
      if (buf[0].length !== frames) throw new Error(`${recipe.id}: expected ${frames} frames, got ${buf[0].length}`);
      normalize(buf, recipe.loudnessDb);
      const seam = seamRatio(buf);
      encode(circularPad(buf, pad), recipe.id, tmp);
      console.log(
        `bed  ${recipe.id.padEnd(16)} ${recipe.seconds}s rms ${(20 * Math.log10(rms(buf))).toFixed(1)}dB ` +
          `peak ${(20 * Math.log10(peak(buf))).toFixed(1)}dB seam ${seam.toFixed(2)} (${Date.now() - started}ms)`,
      );
    }
    for (const recipe of allOneShots) {
      if (only && !only.has(recipe.id)) continue;
      for (let v = 0; v < recipe.variants; v++) {
        const buf = recipe.render(SAMPLE_RATE, mulberry32(seedFrom(`${recipe.id}-${v}`)), v);
        const p = peak(buf);
        const g = dbToGain(recipe.peakDb) / Math.max(p, 1e-9);
        for (const ch of buf) for (let i = 0; i < ch.length; i++) ch[i] *= g;
        encode(buf, `${recipe.id}-${v}`, tmp);
        console.log(`shot ${recipe.id}-${v} ${(buf[0].length / SAMPLE_RATE).toFixed(1)}s`);
      }
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  writeManifest();
}

function writeManifest(): void {
  const files = new Set(readdirSync(outDir));
  const lines: string[] = [
    '// AUTO-GENERATED by synth/build.ts — do not edit by hand.',
    '',
    'export interface BedAsset {',
    '  module: number;',
    '  /** Loop region inside the circularly padded file, in seconds. */',
    '  loopStart: number;',
    '  loopEnd: number;',
    '}',
    '',
    'export const BED_ASSETS: Record<string, BedAsset> = {',
  ];
  for (const r of allBeds) {
    if (!files.has(`${r.id}.mp3`)) continue;
    lines.push(
      `  '${r.id}': { module: require('../../../assets/sounds/${r.id}.mp3'), loopStart: ${LOOP_PAD_SECONDS}, loopEnd: ${
        LOOP_PAD_SECONDS + r.seconds
      } },`,
    );
  }
  lines.push('};', '', 'export const ONE_SHOT_ASSETS: Record<string, number[]> = {');
  for (const r of allOneShots) {
    const mods: string[] = [];
    for (let v = 0; v < r.variants; v++) {
      if (files.has(`${r.id}-${v}.mp3`)) mods.push(`require('../../../assets/sounds/${r.id}-${v}.mp3')`);
    }
    lines.push(`  '${r.id}': [${mods.join(', ')}],`);
  }
  lines.push('};', '');
  writeFileSync(manifestPath, lines.join('\n'));
  console.log(`manifest -> ${manifestPath}`);
}

main();
